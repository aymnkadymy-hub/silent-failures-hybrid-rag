"""Collect every test result into one summary (runs/summary.json + runs/summary.md). All report and paper numbers come
from here; numbers_check.py recomputes a sample of them from the per-seed rows."""
import glob
import json
import os

import numpy as np

RUNS = os.environ.get("RUNS_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "../..", "controller/results"))
POL = ["P0_rrf", "P1_bm25", "P2_dense", "P3_deadarm", "P3r_deadarm_back", "P4_guard_0.75", "P6_healthcheck",
       "P7_farg_static", "G", "G_reg", "G_eps05", "G_dt", "G_disp", "G_vgate", "G_fastrec", "G_kat", "G_noshift",
       "G_norecov", "CIFC_r100", "CIFC_r50", "CIFC_r20", "CIFC_r10", "CIFC_noint", "CIFC_rand", "CIFC_grade",
       "CIFC_gradec", "O_oracle"]


def collect():
    out = {}
    for fn in sorted(glob.glob(os.path.join(RUNS, "t1_test_pool_*.json"))):
        if fn.endswith("_rows.json"):
            continue
        d = json.load(open(fn))
        for s, v in d["agg"].items():
            out.setdefault(("T1", "pool", s), {}).update(v)
    for fn in sorted(glob.glob(os.path.join(RUNS, "tb_*", "test_*.json"))):
        if fn.endswith("_rows.json"):
            continue
        tb = os.path.basename(os.path.dirname(fn))[3:]
        mode = "rerank" if "test_rerank" in fn else "pool"
        d = json.load(open(fn))
        for s, v in d["agg"].items():
            out.setdefault((tb, mode, s), {}).update(v)
    return out


def fmt(x, pct=True, nd=1):
    if x is None:
        return "-"
    return f"{x * 100:.{nd}f}" if pct else f"{x:.0f}"


def fmt_acc(x):
    return "-" if x is None else f"{x:.2f}"


def main():
    res = collect()
    lines = ["# Summary of all test runs (generated by analysis.py)", ""]
    js = {}
    for (tb, mode, s), v in sorted(res.items()):
        pols = [p for p in POL if p in v]
        o = v.get("O_oracle", {})
        lines.append(f"## {tb} / {mode} / {s}")
        lines.append("| policy | Hit@20 | fault-window Hit@20 | healthy-window Hit@20 | Hit@8 (rerank) | lost vs oracle /1000 | "
                     "false suspicions | P(false confirm) | delay suspect | delay confirm | delay recover (n) | exposed | cost | cause acc |")
        lines.append("|" + "---|" * 14)
        for p in pols:
            r = v[p]
            lost = (o.get("h20", 0) - r["h20"]) * 1000 if o else None
            dr = r.get("delay_recover")
            lines.append(
                f"| {p} | {fmt(r['h20'])} | {fmt(r.get('h20_fault'))} | {fmt(r.get('h20_healthy'))} | {fmt(r.get('f8'))} | "
                f"{'-' if lost is None else f'{lost:.1f}'} | {r['false_suspect']:.2f} | {r['frac_false_confirm']:.2f} | "
                f"{fmt(r.get('delay_suspect'), False)} | {fmt(r.get('delay_confirm'), False)} | "
                f"{fmt(dr, False)} ({r.get('delay_recover_n', '-')}) | {r.get('exposed', 0):.1f} | {r.get('cost_units', 0):.0f} | "
                f"{fmt_acc(r.get('cause_acc'))} |")
            js.setdefault(f"{tb}|{mode}|{s}", {})[p] = r
        lines.append("")
    open(os.path.join(RUNS, "summary.md"), "w").write("\n".join(lines))
    json.dump(js, open(os.path.join(RUNS, "summary.json"), "w"), indent=1)
    print(len(res), "scenario blocks")


if __name__ == "__main__":
    main()
